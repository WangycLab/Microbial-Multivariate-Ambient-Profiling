#!/usr/bin/env bash
# run_benchmark.sh — per-sample benchmarking of MVAcaller against knee calling
#
# Adapted from the manuscript pipeline (run_pipeline2.sh). The large-cell and ambient
# read sets are built ONCE per sample; only the synthetic empty / small-cell mixtures
# change between replicates:
#
#   1. split dedup.fq by UMI rank into the top --large-n barcodes (large cells) and the
#      tail from --min-ind on (ambient reads)
#   2. label the large barcodes "#large"
#   3. align + sort the large cells (also the reference used for every mixture)
#
#   per replicate:
#   4. simulate --empty-n empty droplets from the ambient reads  (barcodes "EMPTY*")
#   5. gene-proportional downsampling -> --small-n cells         (barcodes "*#small")
#   6. mix empty + small + large, align, sort
#   7. MVAcaller cell calling
#   8. summary vs the knee UMI threshold
#
# Usage: ./run_benchmark.sh --sample 152 --dedup-fq dedup.fq \
#            --gff ea.gff3 --kegg-map gene_module.tsv --index bowtie2ref/mix3 \
#            --large-n 1000 --small-n 2000 --empty-n 1000 -t 32
set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
REPO_ROOT="$(cd "$SCRIPT_DIR/.." && pwd)"

SAMPLE=""; DEDUP=""; GFF=""; KM=""; INDEX=""; DB=""
LARGE_N=""; SMALL_N=""; EMPTY_N=""; EMPTY_MEAN=100; MIN_IND=100000
COEF_MIN=0.2; COEF_MAX=0.5; KNEE_S=0.7
PVALUE=0.01; SIM_N=10000; IND_MIN=300000; IND_MAX=865739999; UMI_THRE=10000
OUTDIR="results"; REPS=3; THREADS=8; KEEP=0; FORCE=0; DRY_RUN=0

log() { printf '\n[%s] %s\n' "$(date +%H:%M:%S)" "$*"; }
die() { printf '\nERROR: %s\n' "$*" >&2; exit 1; }
need() { command -v "$1" >/dev/null 2>&1 || die "missing dependency: $1"; }
require() { [[ -n "$1" ]] || die "$2 is required (see --help)"; }

usage() {
cat <<'EOF'
Usage: run_benchmark.sh --sample ID --dedup-fq dedup.fq \
           --gff annotation.gff3 --kegg-map gene_module.tsv --index bowtie2ref/ea \
           --large-n 1000 --small-n 2000 --empty-n 1000 [options]

Inputs
  --sample ID           Sample identifier (used in output names)
  --dedup-fq FILE       Deduplicated FASTQ with barcode+UMI in the read name
                        (..._<BC>_<UMI>), e.g. the dedup.fq from mva_dedup.py
  --gff FILE            GFF3 annotation
  --kegg-map FILE       gene -> KEGG module map
  --index PREFIX        Bowtie2 index prefix built from the gene-tagged features

Benchmark sizes (barcodes, all required)
  --large-n INT         Large cells: the top INT barcodes by UMI rank           (--max-ind)
  --small-n INT         Downsampled cells generated by gene-proportional sampling
  --empty-n INT         Simulated empty droplets drawn from the ambient reads
  --empty-mean INT      Mean reads per simulated empty barcode                 [100]
  --min-ind INT         First rank index taken as ambient (must exceed --large-n) [100000]

Simulation and statistics
  --reps INT            Replicates per sample                                  [3]
  --coef-min FLOAT      Downsampling coefficient range                      [0.2]
  --coef-max FLOAT                                                            [0.5]
  --kneedle-s FLOAT     Kneedle sensitivity S                                  [0.7]
  --pvalue FLOAT        MVAcaller combined-P threshold                         [0.01]
  --ind-min INT         Ambient window start rank                              [300000]
  --ind-max INT         Ambient window end rank                            [865739999]

Run control
  -o, --out DIR         Results directory                                      [results]
  -t, --threads INT     Threads for aligner / samtools / MVAcaller             [8]
  --db FILE             Reuse an existing SQLite DB built from the same mixed library
                        (default: build molecules_<sample>_rep<N>.sqlite per replicate)
  --keep                Keep intermediate FASTQ / BAM files
  --force               Rebuild cached reference files and intermediates
  --dry-run             Print commands without executing them
  -h, --help            Show this help
EOF
}

while [[ $# -gt 0 ]]; do
  if [[ "$1" == --*=* ]]; then set -- "${1%%=*}" "${1#*=}" "${@:2}"; fi
  case "$1" in
    --sample)        SAMPLE="$2"; shift 2 ;;
    --dedup-fq)      DEDUP="$2"; shift 2 ;;
    --gff)           GFF="$2"; shift 2 ;;
    --kegg-map)      KM="$2"; shift 2 ;;
    --index)         INDEX="$2"; shift 2 ;;
    --large-n)       LARGE_N="$2"; shift 2 ;;
    --small-n)       SMALL_N="$2"; shift 2 ;;
    --empty-n)       EMPTY_N="$2"; shift 2 ;;
    --empty-mean)    EMPTY_MEAN="$2"; shift 2 ;;
    --min-ind)       MIN_IND="$2"; shift 2 ;;
    --reps)          REPS="$2"; shift 2 ;;
    --coef-min)      COEF_MIN="$2"; shift 2 ;;
    --coef-max)      COEF_MAX="$2"; shift 2 ;;
    --kneedle-s)     KNEE_S="$2"; shift 2 ;;
    --pvalue)        PVALUE="$2"; shift 2 ;;
    --ind-min)       IND_MIN="$2"; shift 2 ;;
    --ind-max)       IND_MAX="$2"; shift 2 ;;
    -o|--out)        OUTDIR="$2"; shift 2 ;;
    -t|--threads)    THREADS="$2"; shift 2 ;;
    --db)            DB="$2"; shift 2 ;;
    --keep)          KEEP=1; shift ;;
    --force)         FORCE=1; shift ;;
    --dry-run)       DRY_RUN=1; shift ;;
    -h|--help)       usage; exit 0 ;;
    *)               die "unknown option: $1 (see --help)" ;;
  esac
done

require "$SAMPLE"   --sample
require "$DEDUP"    --dedup-fq
require "$GFF"      --gff
require "$KM"       --kegg-map
require "$INDEX"    --index
require "$LARGE_N"  --large-n
require "$SMALL_N"  --small-n
require "$EMPTY_N"  --empty-n
(( MIN_IND > LARGE_N )) || die "--min-ind ($MIN_IND) must be greater than --large-n ($LARGE_N)"
if [[ $DRY_RUN == 0 ]]; then
  need python3; need bowtie2; need samtools
fi
# make every path absolute: the rank step runs inside $OUTDIR
abspath() { case "$1" in /*) printf '%s' "$1" ;; *) printf '%s/%s' "$PWD" "$1" ;; esac; }
DEDUP=$(abspath "$DEDUP"); GFF=$(abspath "$GFF"); KM=$(abspath "$KM"); INDEX=$(abspath "$INDEX")
OUTDIR=$(abspath "$OUTDIR")
[[ -z "$DB" ]] || DB=$(abspath "$DB")
mkdir -p "$OUTDIR"

SUMMARY="$OUTDIR/$SAMPLE.summary.tsv"
if [[ ! -s "$SUMMARY" ]]; then
  printf 'sample\trep\tmethod\tlarge\tsmall\tempty\tfdr\n' > "$SUMMARY"
fi

# ---------------------------------------------------------------------------------
# Reference build (once per sample): large cells + ambient reads, shared by all reps
# ---------------------------------------------------------------------------------
LARGE_FQ="$OUTDIR/$SAMPLE.large.fq"
AMBIENT_FQ="$OUTDIR/$SAMPLE.ambient.fq"
LARGE_LABELED="$OUTDIR/$SAMPLE.large.labeled.fq"
LARGE_BAM="$OUTDIR/$SAMPLE.large.bam"
LARGE_SORTED="$OUTDIR/$SAMPLE.large.sorted.bam"

log "Build 1/3 | split dedup.fq by UMI rank"
if [[ -s "$LARGE_FQ" && -s "$AMBIENT_FQ" && $FORCE == 0 ]]; then
  log "reusing $LARGE_FQ and $AMBIENT_FQ"
else
  SPLIT=(python3 "$SCRIPT_DIR/tools/split_by_rank_index.py" -i "$DEDUP"
         --max-ind "$LARGE_N" --min-ind "$MIN_IND"
         -l "$LARGE_FQ" -a "$AMBIENT_FQ")
  log "${SPLIT[*]}"
  [[ $DRY_RUN == 1 ]] || "${SPLIT[@]}"
fi

log "Build 2/3 | label large barcodes with #large"
if [[ -s "$LARGE_LABELED" && $FORCE == 0 ]]; then
  log "reusing $LARGE_LABELED"
else
  log "sed 's/\\(_[ACGT]*\\)_/\\1#large_/' $LARGE_FQ > $LARGE_LABELED"
  [[ $DRY_RUN == 1 ]] || sed 's/\(_[ACGT]*\)_/\1#large_/' "$LARGE_FQ" > "$LARGE_LABELED"
fi

log "Build 3/3 | align and sort the large cells"
if [[ -s "$LARGE_SORTED" && $FORCE == 0 ]]; then
  log "reusing $LARGE_SORTED"
elif [[ $DRY_RUN == 1 ]]; then
  log "bowtie2 -x $INDEX -U $LARGE_FQ --very-sensitive-local -p $THREADS | samtools view -bS - > $LARGE_BAM"
  log "samtools sort -@ $THREADS -o $LARGE_SORTED $LARGE_BAM"
else
  bowtie2 -x "$INDEX" -U "$LARGE_FQ" --very-sensitive-local -p "$THREADS" \
    | samtools view -bS - > "$LARGE_BAM"
  samtools sort -@ "$THREADS" -o "$LARGE_SORTED" "$LARGE_BAM"
fi

# ---------------------------------------------------------------------------------
# Replicates: only the empty / small mixtures are re-drawn
# ---------------------------------------------------------------------------------
for ((REP=1; REP<=REPS; REP++)); do
  SEED_SIM=$((50 + REP)); SEED_SAMP=$((50 + REP)); SEED_TEST=$((56 + REP))
  TAG="${SAMPLE}_rep${REP}"
  PREFIX="$OUTDIR/test_$TAG"
  # one DB per replicate: EMPTY/#small barcodes differ between replicates
  REP_DB="${DB:-$OUTDIR/molecules_$TAG.sqlite}"
  SIM_FQ="$OUTDIR/empty_$TAG.fq"; SMALL_FQ="$OUTDIR/small_$TAG.fq"
  MIX_FQ="$OUTDIR/mix_$TAG.fq"; MIX_BAM="$OUTDIR/mix_$TAG.bam"
  MIX_SORTED="$OUTDIR/mix_$TAG.sorted.bam"; BC_COUNTS="$OUTDIR/counts_$TAG.tsv"

  log "Sample $SAMPLE | replicate $REP/$REPS | seeds sim=$SEED_SIM samp=$SEED_SAMP test=$SEED_TEST"

  # 1. simulate empty droplets from the ambient reads
  log "1/6 simulate empty droplets"
  if [[ $DRY_RUN == 0 ]]; then
    python3 "$SCRIPT_DIR/tools/simulate_empty2.py" -i "$AMBIENT_FQ" -o "$SIM_FQ" \
      -n "$EMPTY_N" --mean "$EMPTY_MEAN" --barcode-prefix EMPTY --seed "$SEED_SIM"
    [[ -s "$SIM_FQ" ]] || die "no empty reads simulated: $AMBIENT_FQ is too small for --empty-n/--empty-mean (lower --min-ind to widen the ambient tail)"
  else
    log "simulate_empty2.py -i $AMBIENT_FQ -o $SIM_FQ -n $EMPTY_N --mean $EMPTY_MEAN --barcode-prefix EMPTY --seed $SEED_SIM"
  fi

  # 2. downsample large cells proportionally to their gene composition
  log "2/6 downsample small cells"
  if [[ $DRY_RUN == 0 ]]; then
    python3 "$SCRIPT_DIR/tools/gene_proportional_sampley.py" -i "$LARGE_FQ" -b "$LARGE_SORTED" \
      -g "$GFF" --gene-module "$KM" -o "$SMALL_FQ" \
      --n-small "$SMALL_N" --coef-min "$COEF_MIN" --coef-max "$COEF_MAX" \
      --seed "$SEED_SAMP" --threads "$THREADS"
  else
    log "gene_proportional_sampley.py -i $LARGE_FQ -b $LARGE_SORTED -g $GFF --gene-module $KM -o $SMALL_FQ --n-small $SMALL_N --coef-min $COEF_MIN --coef-max $COEF_MAX --seed $SEED_SAMP"
  fi

  # 3. mix and align
  log "3/6 mix and align"
  if [[ $DRY_RUN == 0 ]]; then
    cat "$SIM_FQ" "$SMALL_FQ" "$LARGE_LABELED" > "$MIX_FQ"
    bowtie2 -x "$INDEX" -U "$MIX_FQ" --very-sensitive-local -p "$THREADS" \
      | samtools view -bS - > "$MIX_BAM"
    samtools sort -@ "$THREADS" -o "$MIX_SORTED" "$MIX_BAM"
  else
    log "cat $SIM_FQ $SMALL_FQ $LARGE_LABELED > $MIX_FQ"
    log "bowtie2 -x $INDEX -U $MIX_FQ --very-sensitive-local -p $THREADS | samtools view -bS - > $MIX_BAM"
    log "samtools sort -@ $THREADS -o $MIX_SORTED $MIX_BAM"
  fi

  # 4. cell calling
  log "4/6 cell calling"
  MVA=(python3 "$REPO_ROOT/MVAcaller.py" -i "$MIX_SORTED" -g "$GFF" --kegg-map "$KM"
       --build-sqlite "$REP_DB" --reuse-sqlite -o "$PREFIX"
       --threads "$THREADS" --pvalue-thre "$PVALUE" --sim-n "$SIM_N" --seed "$SEED_TEST"
       --umi-thre "$UMI_THRE" --multi-ko split --ambient-pseudocount 1.0
       --ind-min "$IND_MIN" --ind-max "$IND_MAX" --mode-omics)
  log "${MVA[*]}"
  [[ $DRY_RUN == 1 ]] || "${MVA[@]}"

  # 5. summary: MVAcaller calls by class
  log "5/6 summarise cell calls"
  if [[ $DRY_RUN == 0 ]]; then
    [[ -s "$PREFIX.barcodes.tsv" ]] || die "MVAcaller produced no table: $PREFIX.barcodes.tsv"
    read -r CL CS CE NL NS NE TL TS TE < <(
      awk -v TH="$PVALUE" -f "$SCRIPT_DIR/summarize_calls.awk" "$PREFIX.barcodes.tsv")
    FDR=$(awk -v e="$CE" -v l="$CL" -v s="$CS" \
      'BEGIN{t=e+l+s; printf (t? "%.4f":"NA"), (t? e/t : 0)}')
    printf '%s\t%s\tMVAcaller\t%s\t%s\t%s\t%s\n' \
      "$SAMPLE" "$REP" "$CL" "$CS" "$CE" "$FDR" >> "$SUMMARY"
    log "MVAcaller  large=$CL small=$CS empty=$CE (of $TL/$TS/$TE) FDR=$FDR"
    log "third test only  large=$NL small=$NS empty=$NE"
  else
    log "awk -v TH=$PVALUE -f summarize_calls.awk $PREFIX.barcodes.tsv"
  fi

  # 6. knee threshold on the same mixed library
  log "6/6 knee threshold"
  if [[ $DRY_RUN == 0 ]]; then
    [[ -s "$MIX_FQ" ]] || die "missing $MIX_FQ (kept? rerun with --keep)"
    python3 "$SCRIPT_DIR/tools/count_bc.py" -i "$MIX_FQ" -o "$BC_COUNTS" >/dev/null
    THRESH=$(python3 "$REPO_ROOT/mva_knee.py" "$BC_COUNTS" --column umi_count \
      --sensitivity "$KNEE_S" --value umi_threshold)
    read -r KL KS KE < <(awk -F'\t' -v t="$THRESH" '
      NR>1 && $3+0 > t+0 {
        if ($1 ~ /EMPTY/) e++; else if ($1 ~ /#small/) s++; else l++ }
      END { printf "%d\t%d\t%d", l+0, s+0, e+0 }' "$BC_COUNTS")
    KFDR=$(awk -v e="$KE" -v l="$KL" -v s="$KS" 'BEGIN{t=e+l+s; printf (t? "%.4f":"NA"), (t? e/t : 0)}')
    printf '%s\t%s\tknee\t%s\t%s\t%s\t%s\n' "$SAMPLE" "$REP" "$KL" "$KS" "$KE" "$KFDR" >> "$SUMMARY"
    log "knee (S=$KNEE_S, UMI>$THRESH)  large=$KL small=$KS empty=$KE FDR=$KFDR"
  else
    log "count_bc.py -i $MIX_FQ -o $BC_COUNTS"
    log "mva_knee.py $BC_COUNTS --column umi_count --sensitivity $KNEE_S --value umi_threshold"
  fi

  if [[ $KEEP == 0 && $DRY_RUN == 0 ]]; then
    rm -f "$MIX_FQ" "$MIX_BAM" "$MIX_SORTED" "$SIM_FQ" "$SMALL_FQ" "$BC_COUNTS"
  fi
done

[[ $DRY_RUN == 1 ]] && exit 0
log "Results written to $SUMMARY"
column -t -s $'\t' "$SUMMARY"
